from sqlalchemy import Column, Integer, String, Text, DateTime, ForeignKey
from sqlalchemy.sql import func
from sqlalchemy.orm import relationship
from app.database import Base


class HipoteseDiagnostica(Base):
    """
    Diagnostic hypothesis generated by AI (with web search) from the
    anamnesis answers of a consultation.
    """
    __tablename__ = "hipoteses_diagnosticas"

    id = Column(Integer, primary_key=True, index=True)
    consulta_id = Column(Integer, ForeignKey("consultas.id"), nullable=False)
    condicao = Column(String, nullable=False)
    justificativa = Column(Text, nullable=False)
    cid_sugerido = Column(String, nullable=True)  # e.g. "C61" - null if the AI is not confident
    ordem = Column(Integer, nullable=False)  # 1 = most likely hypothesis, in the order returned by the AI
    criado_em = Column(DateTime(timezone=True), server_default=func.now())

    fontes = relationship(
        "FonteHipotese", back_populates="hipotese", cascade="all, delete-orphan"
    )


class FonteHipotese(Base):
    """
    Source/scientific article (PubMed, SciELO, Google Scholar, OMIM,
    Orphanet, GARD/NIH, MedlinePlus) that the AI consulted to support
    a diagnostic hypothesis. A related table (instead of a loose text
    field) so the quantity can be controlled and more can be added later
    (see POST .../mais-fontes).
    """
    __tablename__ = "fontes_hipoteses"

    id = Column(Integer, primary_key=True, index=True)
    hipotese_id = Column(Integer, ForeignKey("hipoteses_diagnosticas.id"), nullable=False)
    titulo = Column(String, nullable=True)
    url = Column(String, nullable=False)
    origem = Column(String, nullable=False)  # ex: "PubMed", "SciELO", "OMIM"

    hipotese = relationship("HipoteseDiagnostica", back_populates="fontes")
